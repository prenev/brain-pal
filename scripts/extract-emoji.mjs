// Extracts the handful of Microsoft Fluent Emoji (MIT) we use from the iconify set into src/lib/emojiData.ts,
// so the app ships only those SVGs and works offline.  Run: node scripts/extract-emoji.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const set = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/fluent-emoji/icons.json', import.meta.url), 'utf8'))

const KEYS = {
  // moods
  'mood-5': 'grinning-squinting-face', 'mood-4': 'slightly-smiling-face', 'mood-3': 'neutral-face', 'mood-2': 'worried-face', 'mood-1': 'loudly-crying-face',
  // emotions
  happy: 'smiling-face-with-smiling-eyes', excited: 'star-struck', grateful: 'smiling-face-with-hearts', relaxed: 'relieved-face', content: 'smiling-face',
  hopeful: 'sunrise', tired: 'sleeping-face', unsure: 'thinking-face', bored: 'expressionless-face', anxious: 'anxious-face-with-sweat', angry: 'pouting-face',
  stressed: 'confounded-face', sad: 'crying-face', lonely: 'pleading-face', overwhelmed: 'face-with-spiral-eyes', ashamed: 'face-with-peeking-eye',
  guilty: 'grimacing-face', afraid: 'fearful-face', desperate: 'weary-face',
  // tags
  work: 'briefcase', family: 'house-with-garden', relationships: 'red-heart', health: 'flexed-biceps', money: 'money-bag', social: 'party-popper',
  sleep: 'crescent-moon', 'self-worth': 'glowing-star', future: 'crystal-ball', past: 'hourglass-not-done', perfectionism: 'bullseye', comparison: 'balance-scale',
  // ui
  fire: 'fire', trophy: 'trophy', bulb: 'light-bulb', memo: 'memo', bubbles: 'bubbles', blueheart: 'blue-heart', sos: 'ring-buoy', seedling: 'seedling',
  herb: 'herb', star: 'star', sparkles: 'sparkles', chart: 'bar-chart', calendar: 'calendar', notebook: 'notebook-with-decorative-cover', wind: 'wind-face',
  gear: 'gear', camera: 'camera', bell: 'bell', party: 'party-popper', muscle: 'flexed-biceps', check: 'check-mark-button', target: 'bullseye', lotus: 'person-in-lotus-position',
  heartfire: 'heart-on-fire', rocket: 'rocket', sunglasses: 'smiling-face-with-sunglasses', hug: 'hugging-face', tada: 'confetti-ball', medal: 'sports-medal',
  photo: 'framed-picture', health2: 'red-heart', cloud: 'cloud', lock: 'locked', phone: 'mobile-phone',
}
const out = {}, missing = []
for (const [k, name] of Object.entries(KEYS)) {
  const ic = set.icons[name] ?? (set.aliases?.[name] && set.icons[set.aliases[name].parent])
  if (ic) out[k] = ic.body; else missing.push(`${k} -> ${name}`)
}
if (missing.length) { console.error('MISSING:', missing.join('\n')); process.exitCode = 1 }
writeFileSync(new URL('../src/lib/emojiData.ts', import.meta.url),
  `// GENERATED by scripts/extract-emoji.mjs from Microsoft Fluent Emoji (MIT). Do not edit.\nexport const EMOJI: Record<string, string> = ${JSON.stringify(out, null, 1)}\n`)
console.log(Object.keys(out).length, 'emoji written')
