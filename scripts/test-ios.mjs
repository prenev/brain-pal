// Guards the JS <-> Swift contract and that the committed Xcode project really contains our native code.
import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'

const read = p => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')

/* 1. the copies inside ios/ are exactly what ios-native/ says (CI caught this drifting once) */
// (the optional `ios-patch.py --apple-signin` entitlement is the only allowed difference)
const stripApple = t => t.replace(/\s*<key>com\.apple\.developer\.applesignin<\/key>\s*<array>.*?<\/array>/s, '').replace(/\s*<key>com\.apple\.developer\.family-controls<\/key>\s*<true\/>/s, '')
for (const f of ['MindfulPlugin.swift', 'MainViewController.swift', 'BrainPalIntents.swift', 'App.entitlements', 'PrivacyInfo.xcprivacy'])
  assert.equal(stripApple(read(`ios/App/App/${f}`)), read(`ios-native/${f}`), `ios/App/App/${f} is stale - run: python3 scripts/ios-patch.py`)

/* 2. every method the JS calls on the Mindful plugin exists in Swift, and vice versa */
const iface = read('src/lib/native.ts').match(/export interface MindfulPlugin \{([\s\S]*?)\n\}/)[1]
const jsMethods = [...iface.matchAll(/^\s{2}(\w+)\(/gm)].map(m => m[1]).filter(m => m !== 'addListener').sort()   // addListener is built into every Capacitor plugin
const swift = read('ios-native/MindfulPlugin.swift')
const swiftRegistered = [...swift.matchAll(/CAPPluginMethod\(name: "(\w+)"/g)].map(m => m[1]).sort()
const swiftImplemented = [...swift.matchAll(/@objc func (\w+)\(_ call: CAPPluginCall\)/g)].map(m => m[1]).sort()
assert.deepEqual(swiftRegistered, jsMethods, 'JS interface and Swift plugin methods differ')
assert.deepEqual(swiftImplemented, jsMethods, 'a registered Swift method has no implementation')
assert.match(swift, /jsName = "Mindful"/); assert.match(read('src/lib/native.ts'), /registerPlugin<MindfulPlugin>\('Mindful'\)/)

/* 3. project wiring */
const pbx = read('ios/App/App.xcodeproj/project.pbxproj')
for (const f of ['MindfulPlugin.swift', 'MainViewController.swift', 'BrainPalIntents.swift'])
  assert.ok(new RegExp(`${f} in Sources`).test(pbx), `${f} must be compiled`)
assert.equal((pbx.match(/CODE_SIGN_ENTITLEMENTS = App\/App\.entitlements/g) ?? []).length, 2, 'entitlements on Debug and Release')
assert.ok(read('ios/App/App/SceneDelegate.swift').includes('MainViewController()'), 'root view controller must register our plugin')
assert.match(read('ios-native/MainViewController.swift'), /registerPluginInstance\(MindfulPlugin\(\)\)/)

/* 4. entitlements + permission strings App Review / iOS require */
assert.match(read('ios/App/App/App.entitlements'), /com\.apple\.developer\.healthkit<\/key>\s*<true\/>/)
const plist = read('ios/App/App/Info.plist')
for (const k of ['NSMicrophoneUsageDescription', 'NSCameraUsageDescription', 'NSPhotoLibraryUsageDescription', 'NSHealthUpdateUsageDescription', 'NSHealthShareUsageDescription'])
  assert.match(plist, new RegExp(`<key>${k}</key>\\s*<string>[^<]{20,}</string>`), `${k} missing or too short`)
assert.match(plist, /<string>brainpal<\/string>/, 'brainpal:// URL scheme')
assert.match(read('capacitor.config.ts'), /appId: 'com\.brainpal\.app'/)
// ios/App/App/capacitor.config.json is generated by `cap sync` (not committed); if present it must agree
if (existsSync(new URL('../ios/App/App/capacitor.config.json', import.meta.url))) assert.equal(JSON.parse(read('ios/App/App/capacitor.config.json')).appId, 'com.brainpal.app')
assert.match(pbx, /PRODUCT_BUNDLE_IDENTIFIER = com\.brainpal\.app/)

/* 4b. social sign-in plumbing */
assert.match(swift, /ASWebAuthenticationSession\(/); assert.match(swift, /ASAuthorizationAppleIDProvider/)
assert.match(swift, /request\.nonce = Self\.sha256\(nonce\)/, 'Apple must receive the hashed nonce, JS the raw one')

/* 4c. native tab bar: a real UITabBar, never restyled (so iOS 26 draws it as Liquid Glass) */
assert.match(swift, /UITabBar\(\)/); assert.match(swift, /UITabBarDelegate/); assert.match(swift, /notifyListeners\("tabSelected"/)
assert.doesNotMatch(swift, /tabBar\??\.(backgroundColor|barTintColor|backgroundImage|standardAppearance|scrollEdgeAppearance|isTranslucent)|bar\.(backgroundColor|barTintColor|backgroundImage|standardAppearance|scrollEdgeAppearance|isTranslucent)/, 'do not restyle the tab bar background: that is what removes the system glass')

/* 4d. Focus guard: Screen Time code is gated on iOS 16, never reads app usage, and the entitlement is opt-in (like Sign in with Apple) */
assert.match(swift, /FamilyActivityPicker/); assert.match(swift, /ManagedSettingsStore/); assert.match(swift, /@available\(iOS 16\.0, \*\)/)
assert.doesNotMatch(swift, /DeviceActivityReport|DeviceActivityCenter|AppUsage/, 'we never read what you use: only shield the apps you chose')
assert.doesNotMatch(read('ios-native/App.entitlements'), /family-controls/, 'the Family Controls entitlement is added by `npm run ios:screentime`, not committed (distribution needs Apple approval)')

/* 4e. Pro subscription: StoreKit 2, one product, same id as the JS side; we only act on verified transactions */
const proJs = read('src/lib/pro.ts').match(/PRODUCT_ID = '([^']+)'/)[1]
assert.ok(swift.includes(`proId = "${proJs}"`), 'Swift product id must equal PRODUCT_ID in src/lib/pro.ts')
assert.match(swift, /Transaction\.currentEntitlements/); assert.match(swift, /Transaction\.updates/); assert.match(swift, /case \.verified\(let tx\)/)
assert.doesNotMatch(swift, /\.unverified/, 'unverified transactions are never trusted')

/* 5. the only health data we ever READ is sleep analysis (privacy promise in the UI and docs) */
assert.equal((swift.match(/HKSampleQuery\(/g) ?? []).length, 1, 'exactly one read query')
assert.match(swift, /HKSampleQuery\(sampleType: sleep,/, 'the one query reads the sleep type'); assert.match(swift, /\.sleepAnalysis/)
assert.doesNotMatch(swift, /HKAnchoredObjectQuery|HKStatisticsQuery|HKStatisticsCollectionQuery|HKQuantityType|HKWorkout|HKCorrelation|HKClinical|HKDocument/, 'no other health data types or query kinds')
const reads = [...swift.matchAll(/read: (\[[^\]]*\])/g)].map(m => m[1]); assert.ok(reads.every(r => r === '[]' || r === '[sleep]'), `only [] or [sleep] may be requested for reading, got ${reads}`)
assert.match(plist, /NSHealthShareUsageDescription<\/key>\s*<string>[^<]*sleep[^<]*<\/string>/, 'the permission text must honestly mention sleep')
assert.doesNotMatch(plist, /does not read your health data/, 'stale claim')
console.log('ios: all tests passed')
